use cargo_snippet::snippet;

#[snippet("適応_シンプソン_積分")]
#[snippet("数値_積分")]
#[snippet("AdaptiveSimpson")]
/// 関数 `f` の区間 `[a, b]` 上の定積分を**適応的シンプソン法**で近似する。許容誤差 `許容誤差`。
///
/// 収束していない所だけ再帰的に細かく刻む。再帰深さは最大 50。
///
/// [`黄金分割探索`](crate::ternary_search) は凸関数の最小化で別目的。
/// 幾何の面積・確率分布・物理量の累積など、閉形式が無い積分に使う。
fn 数値積分<F: Fn(f64) -> f64>(f: &F, a: f64, b: f64, 許容誤差: f64) -> f64 {
    fn 単純<F: Fn(f64) -> f64>(f: &F, a: f64, b: f64) -> f64 {
        let c = (a + b) * 0.5;
        (b - a) / 6.0 * (f(a) + 4.0 * f(c) + f(b))
    }
    #[allow(clippy::too_many_arguments)]
    fn 再帰<F: Fn(f64) -> f64>(
        f: &F, a: f64, b: f64, eps: f64, 全体: f64, 深さ: usize
    ) -> f64 {
        let c = (a + b) * 0.5;
        let 左 = 単純(f, a, c);
        let 右 = 単純(f, c, b);
        let 差 = 左 + 右 - 全体;
        if 深さ == 0 || 差.abs() <= 15.0 * eps {
            return 左 + 右 + 差 / 15.0;
        }
        再帰(f, a, c, eps * 0.5, 左, 深さ - 1) + 再帰(f, c, b, eps * 0.5, 右, 深さ - 1)
    }
    再帰(f, a, b, 許容誤差, 単純(f, a, b), 50)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::f64::consts::{E, PI};

    #[test]
    fn 既知の積分() {
        // ∫_0^1 x² dx = 1/3。
        assert!((数値積分(&|x| x * x, 0.0, 1.0, 1e-9) - 1.0 / 3.0).abs() < 1e-8);
        // ∫_0^π sin x dx = 2。
        assert!((数値積分(&|x: f64| x.sin(), 0.0, PI, 1e-9) - 2.0).abs() < 1e-8);
        // ∫_0^1 4/(1+x²) dx = π。
        assert!((数値積分(&|x| 4.0 / (1.0 + x * x), 0.0, 1.0, 1e-10) - PI).abs() < 1e-8);
        // ∫_0^1 eˣ dx = e − 1。
        assert!((数値積分(&|x: f64| x.exp(), 0.0, 1.0, 1e-10) - (E - 1.0)).abs() < 1e-8);
        // 半円 ∫_{-1}^{1} √(1−x²) dx = π/2（端点で微分が発散するが適応細分で追従）。
        let 半円 = 数値積分(&|x: f64| (1.0 - x * x).max(0.0).sqrt(), -1.0, 1.0, 1e-12);
        assert!((半円 - PI / 2.0).abs() < 1e-4, "半円={半円}");
        // 上下反転（a>b）で符号が反転。
        let 正 = 数値積分(&|x| x * x, 0.0, 2.0, 1e-9);
        let 逆 = 数値積分(&|x| x * x, 2.0, 0.0, 1e-9);
        assert!((正 + 逆).abs() < 1e-8);
    }

    #[test]
    fn 多項式は厳密に近い() {
        // 3 次多項式 ∫_0^2 (x³ − 2x² + x + 5) dx = [x⁴/4 − 2x³/3 + x²/2 + 5x]_0^2
        //   = 4 − 16/3 + 2 + 10 = 16 − 16/3 = 32/3。
        let v = 数値積分(&|x: f64| x.powi(3) - 2.0 * x * x + x + 5.0, 0.0, 2.0, 1e-9);
        assert!((v - 32.0 / 3.0).abs() < 1e-9, "v={v}");
    }
}
