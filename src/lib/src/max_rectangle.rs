/// ヒストグラム内に収まる最大長方形の面積を O(N) で求める（スタック法）。
///
/// `高さ` は各列のバーの高さ。返り値は軸に平行な長方形の最大面積。
///
/// 0/1 グリッドの「全て 1 の最大長方形」は、各行について
/// 「その列まで上に連続する 1 の数」を高さ配列として行ごとにこの関数へ渡せば求まる。
fn ヒストグラム最大長方形(高さ: &[i64]) -> i64 {
    // スタックには (長方形の開始位置, 高さ) を高さ昇順で積む
    let mut スタック: Vec<(usize, i64)> = Vec::new();
    let mut 最大 = 0i64;
    for (i, &h) in 高さ.iter().enumerate() {
        let mut 開始 = i;
        while let Some(&(位置, 積んだ高さ)) = スタック.last() {
            if 積んだ高さ <= h {
                break;
            }
            最大 = 最大.max(積んだ高さ * (i - 位置) as i64);
            開始 = 位置;
            スタック.pop();
        }
        スタック.push((開始, h));
    }
    let n = 高さ.len();
    for (位置, 積んだ高さ) in スタック {
        最大 = 最大.max(積んだ高さ * (n - 位置) as i64);
    }
    最大
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 代表的なヒストグラム() {
        assert_eq!(ヒストグラム最大長方形(&[2, 1, 5, 6, 2, 3]), 10); // 高さ5,6 の幅2 ではなく 5*2=10
        assert_eq!(ヒストグラム最大長方形(&[2, 4]), 4);
        assert_eq!(ヒストグラム最大長方形(&[6, 2, 5, 4, 5, 1, 6]), 12); // 4,5,4,5 の 4*... -> 12
        assert_eq!(ヒストグラム最大長方形(&[3, 3, 3]), 9);
        assert_eq!(ヒストグラム最大長方形(&[]), 0);
    }
}
