use cargo_snippet::snippet;

#[snippet("累乗_mod")]
#[snippet("mod_べき乗")]
#[snippet("繰り返し_二乗法")]
/// `a^e mod 法` を繰り返し二乗法で計算する。`O(log e)`。
///
/// 途中の積を `u128` で取るので `法 < 2^63` まで桁あふれしない。`法 == 1` のときは
/// `1 % 法 == 0` なので `e == 0` でも 0 を返す（数学的に正しい）。
///
/// `ac_library::modint` を使える場面ではそちらの `pow` で足りる。これは法が実行時に
/// 決まる（入力で与えられる・素因数ごとに変わる）ときのための素の実装。
pub fn 累乗_mod(mut a: u64, mut e: u64, 法: u64) -> u64 {
    let mut r = 1u64 % 法;
    a %= 法;
    while e > 0 {
        if e & 1 == 1 {
            r = ((r as u128 * a as u128) % 法 as u128) as u64;
        }
        a = ((a as u128 * a as u128) % 法 as u128) as u64;
        e >>= 1;
    }
    r
}

#[snippet("mod_逆元", include = "累乗_mod")]
#[snippet("フェルマー_逆元")]
/// 素数 `法` を法とする `a` の逆元（フェルマーの小定理 `a^(法-2)`）。`O(log 法)`。
///
/// `法` が素数で `a % 法 != 0` であることが前提。合成数を法とする場合や `a` が
/// `法` の倍数の場合は正しい値を返さない（拡張ユークリッドを使うこと）。
pub fn 逆元(a: u64, 法: u64) -> u64 {
    累乗_mod(a, 法 - 2, 法)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 素朴なべき乗と一致() {
        for 法 in [1u64, 2, 7, 998_244_353] {
            for a in 0u64..20 {
                let mut 期待 = 1u64 % 法;
                for e in 0u64..20 {
                    assert_eq!(累乗_mod(a, e, 法), 期待, "a={a} e={e} 法={法}");
                    期待 = 期待 * (a % 法) % 法;
                }
            }
        }
    }

    #[test]
    fn 大きな法でも桁あふれしない() {
        // 2^61 - 1（メルセンヌ素数）。u64 の素朴な積だとあふれる。
        let 法 = (1u64 << 61) - 1;
        let a = 法 - 3;
        // フェルマーの小定理より a^(法-1) == 1。
        assert_eq!(累乗_mod(a, 法 - 1, 法), 1);
    }

    #[test]
    fn 逆元は積が1になる() {
        let 法 = 998_244_353u64;
        for a in 1u64..50 {
            assert_eq!(a * 逆元(a, 法) % 法, 1, "a={a}");
        }
    }
}
